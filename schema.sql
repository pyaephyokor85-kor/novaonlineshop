-- NOVA virtual fragrance profile storage
-- Run this in Supabase Dashboard -> SQL Editor.

create table if not exists public.fragrance_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  favorite_families text[] not null default '{}',
  preferred_notes text[] not null default '{}',
  moods text[] not null default '{}',
  occasions text[] not null default '{}',
  dislikes text[] not null default '{}',
  last_recommendation text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

grant select, insert, update, delete on public.fragrance_profiles to authenticated;

alter table public.fragrance_profiles enable row level security;

drop policy if exists "Users can view their own fragrance profile" on public.fragrance_profiles;
create policy "Users can view their own fragrance profile"
  on public.fragrance_profiles for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own fragrance profile" on public.fragrance_profiles;
create policy "Users can insert their own fragrance profile"
  on public.fragrance_profiles for insert
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their own fragrance profile" on public.fragrance_profiles;
create policy "Users can update their own fragrance profile"
  on public.fragrance_profiles for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own fragrance profile" on public.fragrance_profiles;
create policy "Users can delete their own fragrance profile"
  on public.fragrance_profiles for delete
  using (auth.uid() = user_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists fragrance_profiles_updated_at on public.fragrance_profiles;
create trigger fragrance_profiles_updated_at
  before update on public.fragrance_profiles
  for each row execute function public.set_updated_at();

-- Optional: one row is created automatically after a new Auth user signs up.
create or replace function public.create_empty_fragrance_profile()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.fragrance_profiles (user_id) values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute function public.create_empty_fragrance_profile();

-- Purchase history used as a preference signal by the Scent Advisor.
create table if not exists public.fragrance_purchases (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null check (product_id ~ '^NV-[0-9]{3}$'),
  purchased_at timestamptz not null default now(),
  quantity integer not null default 1 check (quantity > 0),
  price text,
  created_at timestamptz not null default now()
);

create index if not exists fragrance_purchases_user_date_idx
  on public.fragrance_purchases (user_id, purchased_at desc);

grant select, insert on public.fragrance_purchases to authenticated;
alter table public.fragrance_purchases enable row level security;

drop policy if exists "Users can view their own fragrance purchases" on public.fragrance_purchases;
create policy "Users can view their own fragrance purchases"
  on public.fragrance_purchases for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own fragrance purchases" on public.fragrance_purchases;
create policy "Users can insert their own fragrance purchases"
  on public.fragrance_purchases for insert
  with check (auth.uid() = user_id);
